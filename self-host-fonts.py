#!/usr/bin/env python3
"""Download Manrope, Newsreader, Noto Sans Bengali and Noto Serif Bengali, then switch the app to load them locally.

Run once from the project folder, on a computer with internet:   python3 tools/self-host-fonts.py
It writes fonts/*.woff2 and fonts/fonts.css, and replaces the Google Fonts links in index.html.
After that the app needs no internet for fonts. Bump VERSION in sw.js so installed copies pick up the change.
"""
import re, sys, urllib.request, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONTS = ROOT / "fonts"
KEEP = {"latin", "latin-ext", "bengali"}          # subsets the app needs
CSS_URL = ("https://fonts.googleapis.com/css2?family=Manrope:wght@400;500;600;700;800"
           "&family=Newsreader:opsz,wght@6..72,400;6..72,500;6..72,600"
           "&family=Noto+Sans+Bengali:wght@400;500;600;700&family=Noto+Serif+Bengali:wght@400;500;600&display=swap")
UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36"  # returns woff2

def get(url):
    return urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=60).read()

def convert(css, fetch=get, save=lambda name, data: (FONTS / name).write_bytes(data)):
    """Keep wanted subsets, download each font file, return CSS that points at fonts/<file>."""
    out, done = [], {}
    for m in re.finditer(r"/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{.*?\})", css, re.S):
        subset, block = m.group(1), m.group(2)
        if subset not in KEEP:
            continue
        url = re.search(r"url\((https://[^)]+)\)", block).group(1)
        if url not in done:
            done[url] = f"{len(done) + 1:02d}-" + url.rsplit("/", 1)[-1]
            save(done[url], fetch(url))
        out.append(f"/* {subset} */\n" + block.replace(url, done[url]))
    return "\n".join(out), len(done)

def main():
    FONTS.mkdir(exist_ok=True)
    css, n = convert(get(CSS_URL).decode())
    if not n:
        sys.exit("No font files found. Check your internet connection and try again.")
    (FONTS / "fonts.css").write_text("/* Generated by tools/self-host-fonts.py */\n" + css + "\n")
    html = (ROOT / "index.html").read_text()
    html = re.sub(r'<link rel="preconnect"[^>]*>\s*', "", html)
    html = re.sub(r'<link href="https://fonts\.googleapis\.com[^>]*>', '<link rel="stylesheet" href="fonts/fonts.css">', html)
    (ROOT / "index.html").write_text(html)
    print(f"Done: {n} font files saved in fonts/. index.html now uses fonts/fonts.css.")

if __name__ == "__main__":
    main()
